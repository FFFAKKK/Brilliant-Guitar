import assert from "node:assert/strict";
import test from "node:test";
import { request as httpRequest } from "node:http";
import { StandaloneAgentHost } from "../src/server/agent-host.ts";
import { createStandaloneServer } from "../src/server/http-server.ts";
import { isStandaloneAgentSnapshot } from "../src/contracts/host.ts";
import { createModelFixture, textReply } from "./model-fixture.ts";

test("real completions wire receives separated history and diagnostic GET is private, isolated and read-only", async (t) => {
  const secret = "input-diagnostic-credential-sentinel";
  const long = "长段说明\n".repeat(200) + "完整回答尾部";
  const fixture = await createModelFixture([textReply("连接成功"), textReply("保留20分钟限制"), textReply(long), textReply("节奏改为12分钟"), textReply("第二次连接成功")]);
  const host = new StandaloneAgentHost();
  const server = createStandaloneServer({ host });
  await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
  const address = server.address(); assert.ok(address && typeof address !== "string");
  const url = `http://127.0.0.1:${address.port}/api/model-input`;
  t.after(async () => { await host.dispose(); server.closeAllConnections(); await new Promise<void>((resolve) => server.close(() => resolve())); await fixture.close(); });
  await host.configure({ providerId: "deepseek", protocol: "chat-completions", modelId: "fixture-model", baseUrl: fixture.baseUrl });
  await host.saveCredential(secret);
  assert.equal(await (await fetch(url)).json(), null);
  assert.equal(fixture.requests.length, 0);
  await host.setEnabled(true);
  assert.equal(await host.testConnection(), true);
  assert.equal(host.getModelInput(), null);
  await host.session.submit("我每天20分钟，优先练节奏");
  await host.session.submit("详细解释节奏训练的原理");
  await host.session.submit("节奏部分改成12分钟");
  const body = fixture.requests[3]!.body;
  const messages = body.messages as { role: string; content: string }[];
  assert.deepEqual(messages.map((item) => item.role), ["system", "user", "assistant", "user", "assistant", "user"]);
  assert.match(messages[0]!.content, /通用任务助手/);
  assert.equal(messages[1]!.content, "我每天20分钟，优先练节奏");
  assert.equal(messages[4]!.content, long);
  assert.equal(JSON.stringify(body).split("节奏部分改成12分钟").length - 1, 1);
  const current = JSON.parse(messages[5]!.content) as { modelConfiguration: Record<string, unknown> };
  assert.deepEqual(current.modelConfiguration, { kind: "host-routing-configuration", providerId: "deepseek", modelId: "fixture-model", modelApi: "openai-completions", identityVerified: false });
  assert.deepEqual(body.thinking, { type: "disabled" });
  assert.equal(body.max_tokens, 1500);
  const diagnostic = host.getModelInput(); assert.ok(diagnostic);
  const response = await fetch(url); assert.equal(response.status, 200); assert.equal(response.headers.get("cache-control"), "no-store");
  assert.deepEqual(await response.json(), diagnostic);
  assert.deepEqual(diagnostic.roles, messages.map((item) => item.role));
  assert.equal(diagnostic.instructionsVersion, "general-task-v1");
  assert.equal(diagnostic.retainedHistoryTurns, 2);
  assert.equal(diagnostic.timeoutMs, 45000);
  assert.equal(diagnostic.maxOutputTokens, body.max_tokens);
  const diagnosticText = JSON.stringify(diagnostic);
  for (const excluded of [secret, fixture.baseUrl, long, "详细解释节奏训练的原理"]) assert.ok(!diagnosticText.includes(excluded));
  assert.equal(fixture.requests.length, 4);
  assert.equal((await fetch(url, { headers: { origin: "http://other.local" } })).status, 403);
  assert.equal(await new Promise<number | undefined>((resolve, reject) => {
    const req = httpRequest(url, { headers: { host: "other.local" } }, (res) => { res.resume(); resolve(res.statusCode); }); req.on("error", reject); req.end();
  }), 403);
  assert.ok(isStandaloneAgentSnapshot(host.getSnapshot()));
  // An explicit probe after a real request cannot replace its diagnostic or history.
  assert.equal(await host.testConnection(), true);
  assert.equal(host.getModelInput(), diagnostic);
  assert.equal(host.getSnapshot().session.messages.length, 6);
  const previousSessionId = host.getSnapshot().session.sessionId;
  await host.reset();
  assert.equal(await (await fetch(url)).json(), null);
  await host.selectConversation(previousSessionId);
  assert.equal(host.getModelInput(), null);
  assert.equal(fixture.requests.length, 5);
  await host.dispose(); assert.equal(host.getModelInput(), null);
});
